#!/usr/bin/env python3
"""
LocalRedact.py

Local-only PDF redaction for documents commonly sent to/from wealth managers.
No cloud API or Ollama. Can run as a local-only HTTP API on 127.0.0.1.

Required:
    pip install pymupdf boto3

For local HTTP API mode:
    pip install fastapi uvicorn python-multipart

Optional, for better free-form person-name detection:
    pip install spacy
    python -m spacy download en_core_web_sm

Usage:
    python LocalRedact.py input.pdf --client-id client-001
    python LocalRedact.py a.pdf b.pdf --client-id client-001
    python LocalRedact.py input.pdf --client-id client-001 --no-ner

After each redaction batch, the generated redacted PDFs are zipped together
and uploaded to S3 under uploads/<client_id>/<zip-name>.zip. AWS credentials
are read by boto3 from the normal AWS credential chain / environment.

If no input file is supplied, the script opens a local file picker when Tkinter
is available.

Important:
- Best on PDFs that already contain selectable/searchable text.
- Scanned/image-only PDFs need OCR first, or manual redaction boxes.
- Handwritten/image signatures are not reliably detectable by this lightweight
  script. Use --manual-boxes for them.

Manual boxes JSON example, using PDF coordinates in points:
[
  {"page": 1, "rect": [100, 200, 300, 260], "category": "manual_signature"}
]
Page numbers are 1-based.
"""

