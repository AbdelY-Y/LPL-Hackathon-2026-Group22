# ----------------------------
# S3 batch upload configuration
# ----------------------------

DEFAULT_S3_BUCKET = os.environ.get(
    "AWS_UPLOAD_BUCKET",
    "lpl-financial-docs-team-10-2026-020467507399-us-east-1-an",
)
DEFAULT_AWS_REGION = os.environ.get("AWS_DEFAULT_REGION", "us-east-1")
DEFAULT_CLIENT_ID = os.environ.get("CLIENT_ID", "DeploymentData")


def safe_client_id(value: str) -> str:
    """Return a safe S3 path component for a wealth-management client ID."""
    value = re.sub(r"[^A-Za-z0-9._-]+", "_", (value or "").strip()).strip("._")
    if not value:
        raise ValueError("client_id cannot be empty")
    return value[:120]


def create_redacted_zip(
    results: list[dict[str, Any]],
    output_dir: str | Path,
    client_id: str,
) -> Path:
    """Zip only the redacted PDFs generated by the current batch."""
    if not results:
        raise ValueError("No redacted files were generated.")

    output_root = Path(output_dir).expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    client = safe_client_id(client_id)
    zip_path = output_root / f"redacted_{client}_{uuid.uuid4().hex[:12]}.zip"

    with zipfile.ZipFile(
        zip_path,
        mode="w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=6,
    ) as archive:
        for item in results:
            file_path = Path(item["output_path"]).expanduser().resolve()
            if not file_path.is_file():
                raise FileNotFoundError(f"Redacted output not found: {file_path}")

            # Store only the redacted PDF filename inside the archive.
            archive.write(file_path, arcname=file_path.name)

    return zip_path


def upload_zip_to_s3(
    zip_path: str | Path,
    client_id: str,
    *,
    bucket: str = DEFAULT_S3_BUCKET,
    region: str = DEFAULT_AWS_REGION,
) -> dict[str, str]:
    """
    Upload the redacted batch ZIP to:
        uploads/<client_id>/<zip_filename>

    No AWS secrets are stored in this source file. boto3 reads credentials from
    environment variables, ~/.aws/credentials, IAM roles, or another standard
    AWS credential provider.
    """
    try:
        import boto3
    except ImportError as exc:
        raise RuntimeError(
            "S3 upload requires boto3. Install it with: pip install boto3"
        ) from exc

    zip_file = Path(zip_path).expanduser().resolve()
    if not zip_file.is_file():
        raise FileNotFoundError(f"ZIP file not found: {zip_file}")

    client = safe_client_id(client_id)
    key = f"uploads/{client}/{zip_file.name}"

    s3 = boto3.client("s3", region_name=region)
    s3.upload_file(
        str(zip_file),
        bucket,
        key,
        ExtraArgs={"ContentType": "application/zip"},
    )

    return {
        "bucket": bucket,
        "key": key,
        "s3_uri": f"s3://{bucket}/{key}",
    }


# ----------------------------
# Structured PII patterns
# ----------------------------

EMAIL_RE = re.compile(r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", re.I)
PHONE_RE = re.compile(
    r"(?<![\d(])(?:\+?1[ .-]?)?(?:\(\d{3}\)|\d{3})[ .-]\d{3}[ .-]\d{4}(?!\d)"
)
SSN_RE = re.compile(r"(?<!\d)\d{3}-\d{2}-\d{4}(?!\d)")
EIN_RE = re.compile(r"(?<!\d)\d{2}-\d{7}(?!\d)")
DOB_RE = re.compile(
    r"(?i)\b(?:DOB|date\s+of\s+birth|birth\s+date)\s*[:#-]?\s*"
    r"((?:0?[1-9]|1[0-2])[/-](?:0?[1-9]|[12]\d|3[01])[/-](?:19|20)\d{2}|"
    r"(?:19|20)\d{2}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01]))"
)

# Common US street suffixes. Intentionally narrow to reduce false positives.
STREET_SUFFIX = (
    r"Street|St\.?|Avenue|Ave\.?|Road|Rd\.?|Lane|Ln\.?|Drive|Dr\.?|"
    r"Boulevard|Blvd\.?|Court|Ct\.?|Way|Parkway|Pkwy\.?|Place|Pl\.?|"
    r"Terrace|Ter\.?|Circle|Cir\.?|Highway|Hwy\.?")
STREET_RE = re.compile(
    rf"(?<!\w)\d{{1,6}}\s+[A-Za-z0-9.'#&/-]+(?:\s+[A-Za-z0-9.'#&/-]+){{0,8}}\s+"
    rf"(?:{STREET_SUFFIX})\b(?:\s+(?:Apt\.?|Unit|Suite|Ste\.?|#)\s*[A-Za-z0-9-]+)?",
    re.I,
)
POBOX_RE = re.compile(r"\bP\.?\s*O\.?\s+Box\s+\d+[A-Za-z0-9-]*\b", re.I)
CITY_STATE_ZIP_RE = re.compile(
    r"\b[A-Za-z][A-Za-z .'-]{1,50},\s*[A-Z]{2}\s+\d{5}(?:-\d{4})?\b"
)

# Useful for account-like values that get separated from their field label by PDF layout.
GENERIC_HYPHENATED_ID_RE = re.compile(r"(?<!\d)\d{6,12}-\d{2,6}(?!\d)")
PREFIXED_ID_RE = re.compile(r"\b(?:AUTH|CLM|MEM|EMP|PT|TRC|REF|CONF|CASE)-[A-Z0-9-]{4,}\b", re.I)
LEADING_NAME_RE = re.compile(
    r"^\s*([A-Z][a-z'\-]+(?:\s+[A-Z][a-z'\-]+){1,3})\s{2,}"
    r"(?:Account|Policy|DOB|SSN|TIN|Address|Client|Borrower|Investor|Employee|"
    r"Patient|Member|Vehicle|Provider|Pay|Statement|ID)\b"
)

# Values after field labels commonly seen in wealth-management paperwork.
# Post-filtering requires a digit so ordinary words like "summary" are not redacted.
LABELED_ID_RE = re.compile(
    r"(?i)\b(?:"
    r"account(?:\s+(?:number|no\.?|#|ending))?|acct(?:\.|\s+(?:no\.?|#))?|"
    r"bank\s+account|routing(?:\s+(?:number|no\.?|#))?|ABA|"
    r"taxpayer\s+id|tax\s+id|TIN|SSN|social\s+security(?:\s+number)?|"
    r"client\s+(?:id|number)|household\s+(?:id|number)|customer\s+id|"
    r"employee\s+id|patient\s+id|member(?:\s+(?:id|number))?|ID|NPI|"
    r"policy(?:\s+(?:number|no\.?|#))?|loan(?:\s+(?:number|no\.?|#))?|"
    r"mortgage(?:\s+(?:number|no\.?|#))?|card\s+(?:id|number)|"
    r"direct\s+deposit|brokerage\s+account|retirement\s+account|IRA\s+account|"
    r"statement\s+id|claim(?:\s+(?:number|no\.?|#|reference))?|"
    r"authorization(?:\s+(?:number|no\.?|#))?|VIN|"
    r"passport(?:\s+(?:number|no\.?|#))?|driver'?s\s+license(?:\s+(?:number|no\.?|#))?|"
    r"government\s+id|group(?:\s+(?:number|no\.?|#))?|"
    r"servicer\s+code|bank\s+code|institution\s+code|broker\s+ref(?:erence)?|preparer\s+ref(?:erence)?|"
    r"clearing\s+code|payroll\s+trace|trace(?:\s+(?:number|no\.?|#))?|"
    r"reference(?:\s+(?:number|no\.?|#))?|confirmation(?:\s+(?:number|no\.?|#))?|"
    r"meter(?:\s+(?:number|no\.?|#))?"
    r")\s*[:#=-]?\s*"
    r"([A-Z0-9][A-Z0-9*._/#-]{3,})"
)

# Names following common client/person labels.
NAME_LABEL_RE = re.compile(
    r"(?i)\b(?:"
    r"client|account\s+holder|account\s+owner|owner|borrower|investor|"
    r"taxpayer|filer|employee|patient|guarantor|named\s+insured|insured|"
    r"beneficiary|trustee|grantor|settlor|authorized\s+person|advisor|adviser|"
    r"representative|prepared\s+for|attention|attn\."
    r")\s*[:#-]?\s*"
    r"([A-Z][A-Za-z'-]+(?:\s+(?:[A-Z][A-Za-z'-]+|[A-Z]\.?)){1,4})"
)

TRUST_ESTATE_RE = re.compile(
    r"(?i)\b(?:trust|estate|entity|registration|account\s+title)\s*[:#-]?\s*"
    r"([A-Z][A-Za-z0-9&'.\- ]{2,80}?(?:Trust|Estate|Family\s+Trust|Living\s+Trust))\b"
)

EMPLOYER_RE = re.compile(
    r"(?i)\b(?:employer|employer\s+name|company\s+name)\s*[:#-]?\s*"
    r"([A-Z][A-Za-z0-9&'.\-, ]{2,80})"
)

CARD_CANDIDATE_RE = re.compile(r"(?<!\d)(?:\d[ -]?){13,19}(?!\d)")
PERSON_LINE_RE = re.compile(
    r"^\s*([A-Z][A-Za-z'-]+(?:\s+(?:[A-Z][A-Za-z'-]+|[A-Z]\.?)){1,3})\s*$"
)

NON_NAME_WORDS = {
    "personal", "checking", "statement", "monthly", "quarterly", "annual",
    "account", "summary", "payment", "electric", "service", "federal",
    "tax", "filing", "worksheet", "earnings", "insurance", "policy",
    "brokerage", "mortgage", "capital", "energy", "health", "system",
    "student", "servicing", "bank", "card", "services", "company", "co",
    "llc", "inc", "corp", "corporation", "holdings", "investment", "due",
    "paid", "billing", "status", "id", "ssn", "tin", "dept", "location",
    "balance", "plan", "reference", "advice", "snapshot", "portal",
    "pay", "period", "vehicle", "provider", "property", "borrower", "investor",
    "patient", "insured", "beneficiary", "trustee", "grantor", "advisor", "adviser",
}

NAME_STOP_WORDS = {
    "filing", "status", "id", "ssn", "tin", "account", "card", "policy",
    "dept", "department", "location", "due", "dob", "address", "member",
    "customer", "employee", "loan", "group", "claim", "authorization",
    "routing", "bank", "statement", "pay", "period", "vehicle", "provider",
    "property", "frequency",
}


@dataclass(frozen=True)
class Finding:
    page_index: int
    category: str
    text: str
    rect: Optional[tuple[float, float, float, float]] = None


def clean_match(value: str) -> str:
    return value.strip(" \t\r\n,:;|[]()")


def luhn_ok(raw: str) -> bool:
    digits = re.sub(r"\D", "", raw)
    if not 13 <= len(digits) <= 19 or len(set(digits)) == 1:
        return False
    total = 0
    parity = len(digits) % 2
    for i, ch in enumerate(digits):
        n = int(ch)
        if i % 2 == parity:
            n *= 2
            if n > 9:
                n -= 9
        total += n
    return total % 10 == 0


def unique_findings(findings: Iterable[Finding]) -> list[Finding]:
    out: list[Finding] = []
    seen = set()
    for finding in findings:
        key = (finding.page_index, finding.category, finding.text, finding.rect)
        if key not in seen:
            seen.add(key)
            out.append(finding)
    return out


def looks_like_address(line: str) -> bool:
    return bool(STREET_RE.search(line) or POBOX_RE.search(line) or CITY_STATE_ZIP_RE.search(line))


def normalize_person_name(value: str) -> str:
    """Trim field-label spillover and reject obvious non-person text."""
    value = clean_match(value)
    tokens = value.split()
    kept: list[str] = []
    for token in tokens:
        key = token.lower().strip(".:,#-()")
        if kept and key in NAME_STOP_WORDS:
            break
        kept.append(token)
    value = " ".join(kept)
    words = [w.lower().strip(".'-,") for w in value.split()]
    if len(words) < 2:
        return ""
    if any(word in NON_NAME_WORDS for word in words):
        return ""
    return value


def detect_text_findings(page_index: int, text: str, use_ner: bool, nlp) -> list[Finding]:
    findings: list[Finding] = []

    for category, regex in (
        ("email", EMAIL_RE),
        ("phone", PHONE_RE),
        ("ssn", SSN_RE),
        ("tax_id", EIN_RE),
    ):
        for match in regex.finditer(text):
            findings.append(Finding(page_index, category, clean_match(match.group(0))))

    for match in DOB_RE.finditer(text):
        findings.append(Finding(page_index, "date_of_birth", clean_match(match.group(1))))

    for match in GENERIC_HYPHENATED_ID_RE.finditer(text):
        findings.append(Finding(page_index, "unique_identifier", clean_match(match.group(0))))
    for match in PREFIXED_ID_RE.finditer(text):
        findings.append(Finding(page_index, "unique_identifier", clean_match(match.group(0))))

    lines = [line.strip() for line in text.splitlines() if line.strip()]
    for i, line in enumerate(lines):
        if line.lower().startswith("dataset record"):
            continue

        for match in LABELED_ID_RE.finditer(line):
            value = clean_match(match.group(1))
            if value and any(ch.isdigit() for ch in value):
                findings.append(Finding(page_index, "labeled_identifier", value))

        for match in NAME_LABEL_RE.finditer(line):
            value = normalize_person_name(match.group(1))
            if value:
                findings.append(Finding(page_index, "name", value))

        for match in TRUST_ESTATE_RE.finditer(line):
            value = clean_match(match.group(1))
            if value:
                findings.append(Finding(page_index, "trust_or_estate_name", value))

        for match in EMPLOYER_RE.finditer(line):
            value = clean_match(match.group(1))
            if value:
                findings.append(Finding(page_index, "employer", value))

        for match in STREET_RE.finditer(line):
            findings.append(Finding(page_index, "street_address", clean_match(match.group(0))))
        for match in POBOX_RE.finditer(line):
            findings.append(Finding(page_index, "po_box", clean_match(match.group(0))))
        for match in CITY_STATE_ZIP_RE.finditer(line):
            findings.append(Finding(page_index, "city_state_zip", clean_match(match.group(0))))

        # Common statement header layout: "Avery Rowan        Account number".
        leading = LEADING_NAME_RE.match(line)
        if leading:
            candidate = normalize_person_name(leading.group(1))
            if candidate:
                findings.append(Finding(page_index, "name", candidate))

        standalone = PERSON_LINE_RE.match(line)
        if standalone:
            candidate = normalize_person_name(standalone.group(1))
            adjacent_address = (
                (i + 1 < len(lines) and looks_like_address(lines[i + 1])) or
                (i + 2 < len(lines) and looks_like_address(lines[i + 2])) or
                (i > 0 and looks_like_address(lines[i - 1]))
            )
            if candidate and adjacent_address:
                findings.append(Finding(page_index, "name", candidate))

        due_name = re.match(
            r"^([A-Z][A-Za-z'-]+(?:\s+[A-Z][A-Za-z'-]+){1,3})\s+Due\b",
            line,
        )
        if due_name:
            candidate = normalize_person_name(due_name.group(1))
            if candidate:
                findings.append(Finding(page_index, "name", candidate))

    for match in CARD_CANDIDATE_RE.finditer(text):
        candidate = clean_match(match.group(0))
        if luhn_ok(candidate):
            findings.append(Finding(page_index, "payment_card", candidate))

    if use_ner and nlp is not None and text.strip():
        try:
            nlp_doc = nlp(text)
            for ent in nlp_doc.ents:
                if ent.label_ == "PERSON":
                    value = normalize_person_name(ent.text)
                    if value:
                        findings.append(Finding(page_index, "name_ner", value))
        except Exception as exc:
            print(f"Warning: local NER failed on page {page_index + 1}: {exc}", file=sys.stderr)

    return unique_findings(findings)


def load_spacy_model(disabled: bool):
    if disabled:
        return None
    try:
        import spacy
    except ImportError:
        print(
            "Note: spaCy is not installed. Using regex/label-based detection only. "
            "For stronger local name detection: pip install spacy && "
            "python -m spacy download en_core_web_sm",
            file=sys.stderr,
        )
        return None

    try:
        return spacy.load(
            "en_core_web_sm",
            disable=["tagger", "parser", "lemmatizer", "attribute_ruler"],
        )
    except Exception:
        print(
            "Note: spaCy is installed but en_core_web_sm is unavailable. "
            "Using regex/label-based detection only. Install it with: "
            "python -m spacy download en_core_web_sm",
            file=sys.stderr,
        )
        return None


def add_text_redactions(page, finding: Finding, padding: float) -> int:
    """Find visible text and add true redaction annotations."""
    if not finding.text:
        return 0

    try:
        rects = page.search_for(finding.text, quads=False)
    except Exception:
        rects = []

    if not rects and " " in finding.text:
        compact = " ".join(finding.text.split())
        if compact != finding.text:
            try:
                rects = page.search_for(compact, quads=False)
            except Exception:
                rects = []

    count = 0
    for rect in rects:
        padded = fitz.Rect(
            rect.x0 - padding,
            rect.y0 - padding,
            rect.x1 + padding,
            rect.y1 + padding,
        )
        padded &= page.rect
        page.add_redact_annot(padded, fill=(0, 0, 0))
        count += 1
    return count


def load_manual_boxes(path: Optional[str]) -> list[Finding]:
    if not path:
        return []

    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError("manual-boxes JSON must contain a list")

    findings: list[Finding] = []
    for item in data:
        page_no = int(item["page"])
        rect = item["rect"]
        if len(rect) != 4:
            raise ValueError("Each manual rect must be [x0, y0, x1, y1]")
        findings.append(
            Finding(
                page_index=page_no - 1,
                category=str(item.get("category", "manual")),
                text="",
                rect=tuple(float(v) for v in rect),
            )
        )
    return findings


def redact_pdf(
    input_path: str,
    output_path: str,
    *,
    password: Optional[str] = None,
    nlp=None,
    padding: float = 1.5,
    manual_boxes_path: Optional[str] = None,
    audit_path: Optional[str] = None,
) -> tuple[int, Counter, list[int]]:
    manual = load_manual_boxes(manual_boxes_path)

    doc = fitz.open(input_path)
    try:
        if doc.needs_pass:
            if not password or not doc.authenticate(password):
                raise ValueError("PDF is password-protected. Supply the correct --password.")

        manual_by_page: dict[int, list[Finding]] = {}
        for finding in manual:
            manual_by_page.setdefault(finding.page_index, []).append(finding)

        total_redactions = 0
        category_counts: Counter = Counter()
        low_text_pages: list[int] = []
        audit_rows: list[dict] = []

        for page_index, page in enumerate(doc):
            text = page.get_text("text", sort=True) or ""
            if len(re.sub(r"\s", "", text)) < 8:
                low_text_pages.append(page_index + 1)

            findings = detect_text_findings(page_index, text, nlp is not None, nlp)
            annotations_added = 0

            for finding in findings:
                count = add_text_redactions(page, finding, padding)
                if count:
                    annotations_added += count
                    category_counts[finding.category] += count
                    audit_rows.append(
                        {
                            "page": page_index + 1,
                            "category": finding.category,
                            "occurrences": count,
                        }
                    )

            for finding in manual_by_page.get(page_index, []):
                rect = fitz.Rect(*finding.rect)
                rect &= page.rect
                if not rect.is_empty:
                    page.add_redact_annot(rect, fill=(0, 0, 0))
                    annotations_added += 1
                    category_counts[finding.category] += 1
                    audit_rows.append(
                        {
                            "page": page_index + 1,
                            "category": finding.category,
                            "occurrences": 1,
                        }
                    )

            if annotations_added:
                page.apply_redactions(
                    images=fitz.PDF_REDACT_IMAGE_PIXELS,
                    graphics=fitz.PDF_REDACT_LINE_ART_REMOVE_IF_TOUCHED,
                    text=fitz.PDF_REDACT_TEXT_REMOVE,
                )
                total_redactions += annotations_added

        # Remove hidden content and metadata that can leak identities after visible redaction.
        try:
            doc.scrub(
                attached_files=True,
                clean_pages=True,
                embedded_files=True,
                hidden_text=True,
                javascript=True,
                metadata=True,
                redactions=False,
                remove_links=False,
                reset_fields=True,
                reset_responses=True,
                thumbnails=True,
                xml_metadata=True,
            )
        except Exception as exc:
            print(f"Warning: PDF scrub step could not fully run: {exc}", file=sys.stderr)
            try:
                doc.set_metadata({})
            except Exception:
                pass

        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)
        doc.save(str(output), garbage=4, deflate=True, clean=True)

        if audit_path:
            payload = {
                "input": Path(input_path).name,
                "output": Path(output_path).name,
                "total_redaction_annotations": total_redactions,
                "categories": dict(category_counts),
                "image_only_or_low_text_pages": low_text_pages,
                "details": audit_rows,
                "note": "Matched PII values are intentionally omitted from this audit file.",
            }
            Path(audit_path).write_text(json.dumps(payload, indent=2), encoding="utf-8")

        return total_redactions, category_counts, low_text_pages
    finally:
        doc.close()


def choose_file_gui() -> Optional[str]:
    try:
        import tkinter as tk
        from tkinter import filedialog
    except Exception:
        return None

    root = tk.Tk()
    root.withdraw()
    try:
        return filedialog.askopenfilename(
            title="Choose PDF to redact",
            filetypes=[("PDF files", "*.pdf"), ("All files", "*.*")],
        ) or None
    finally:
        root.destroy()


def safe_output_stem(filename: str) -> str:
    """Return a filesystem-safe stem without trusting an uploaded path."""
    stem = Path(Path(filename).name).stem
    stem = re.sub(r"[^A-Za-z0-9._-]+", "_", stem).strip("._")
    if not stem:
        stem = "document"
    return stem[:120]


def make_uuid_output_path(input_name: str, output_dir: str | Path) -> Path:
    output_dir = Path(output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir / f"{safe_output_stem(input_name)}_{uuid.uuid4()}.pdf"


def redact_files(
    input_paths: Iterable[str | Path],
    output_dir: str | Path,
    *,
    password: Optional[str] = None,
    no_ner: bool = False,
    padding: float = 1.5,
) -> list[dict[str, Any]]:
    """
    Redact multiple local PDFs and return metadata for each generated file.

    This is also useful if another Python program imports LocalRedact directly.
    Other languages should normally use the local HTTP API exposed by --serve.
    """
    output_root = Path(output_dir).expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)
    nlp = load_spacy_model(no_ner)

    results: list[dict[str, Any]] = []
    for raw_path in input_paths:
        input_path = Path(raw_path).expanduser().resolve()
        if not input_path.is_file():
            raise FileNotFoundError(f"Input file not found: {input_path}")
        if input_path.suffix.lower() != ".pdf":
            raise ValueError(f"Input must be a PDF: {input_path}")

        output_path = make_uuid_output_path(input_path.name, output_root)
        total, counts, low_text_pages = redact_pdf(
            str(input_path),
            str(output_path),
            password=password,
            nlp=nlp,
            padding=padding,
        )
        results.append(
            {
                "input_file": input_path.name,
                "output_file": output_path.name,
                "output_path": str(output_path),
                "total_redactions": total,
                "categories": dict(counts),
                "image_only_or_low_text_pages": low_text_pages,
            }
        )
    return results


def create_api_app(
    output_dir: str | Path,
    *,
    no_ner: bool = False,
    padding: float = 1.5,
    s3_bucket: str = DEFAULT_S3_BUCKET,
    aws_region: str = DEFAULT_AWS_REGION,
):
    """Create a FastAPI app that accepts a list of PDF uploads."""
    try:
        from fastapi import FastAPI, File, Form, HTTPException, UploadFile
        from fastapi.middleware.cors import CORSMiddleware
        from fastapi.responses import FileResponse
    except ImportError as exc:
        raise RuntimeError(
            "API mode needs: pip install fastapi uvicorn python-multipart"
        ) from exc

    output_root = Path(output_dir).expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    # Load the optional local NER model once when the API starts, not once per PDF.
    nlp = load_spacy_model(no_ner)

    app = FastAPI(
        title="LocalRedact API",
        version="2.0",
        description=(
            "Local-only wealth-management PDF redaction. Files are processed on "
            "this machine and written to the configured output directory."
        ),
    )

    # Allow browser frontends running locally. Native apps / C# / Java / etc.
    # are not subject to browser CORS restrictions.
    app.add_middleware(
        CORSMiddleware,
        allow_origins=["null"],
        allow_origin_regex=r"^https?://(localhost|127\.0\.0\.1)(:\d+)?$",
        allow_credentials=False,
        allow_methods=["GET", "POST"],
        allow_headers=["*"],
    )

    @app.get("/health")
    def health():
        return {
            "status": "ok",
            "output_dir": str(output_root),
            "ner_enabled": nlp is not None,
            "s3_bucket": s3_bucket,
            "aws_region": aws_region,
        }

    @app.post("/redact")
    async def redact_uploads(
        files: list[UploadFile] = File(...),
        client_id: str = Form(DEFAULT_CLIENT_ID),
    ):
        """
        Upload one or more PDFs under the repeated multipart field name `files`.

        Returns both a simple `output_paths` list and a detailed `outputs` list.
        No matched PII text is returned by the API.
        """
        if not files:
            raise HTTPException(status_code=400, detail="Upload at least one PDF.")

        results: list[dict[str, Any]] = []
        with tempfile.TemporaryDirectory(prefix="localredact_") as temp_dir:
            temp_root = Path(temp_dir)

            for upload in files:
                original_name = Path(upload.filename or "document.pdf").name
                if Path(original_name).suffix.lower() != ".pdf":
                    await upload.close()
                    raise HTTPException(
                        status_code=400,
                        detail=f"Only PDF uploads are supported: {original_name}",
                    )

                temp_input = temp_root / f"{uuid.uuid4()}.pdf"
                try:
                    with temp_input.open("wb") as destination:
                        while True:
                            chunk = await upload.read(1024 * 1024)
                            if not chunk:
                                break
                            destination.write(chunk)
                finally:
                    await upload.close()

                # Quick signature check to reject a renamed non-PDF file.
                try:
                    with temp_input.open("rb") as check:
                        if check.read(5) != b"%PDF-":
                            raise HTTPException(
                                status_code=400,
                                detail=f"File is not a valid PDF: {original_name}",
                            )
                except OSError as exc:
                    raise HTTPException(status_code=400, detail=str(exc)) from exc

                output_path = make_uuid_output_path(original_name, output_root)
                try:
                    total, counts, low_text_pages = redact_pdf(
                        str(temp_input),
                        str(output_path),
                        nlp=nlp,
                        padding=padding,
                    )
                except Exception as exc:
                    # Do not leave a partial output if processing fails.
                    try:
                        output_path.unlink(missing_ok=True)
                    except Exception:
                        pass
                    raise HTTPException(
                        status_code=500,
                        detail=f"Failed to redact {original_name}: {exc}",
                    ) from exc

                results.append(
                    {
                        "input_file": original_name,
                        "output_file": output_path.name,
                        "output_path": str(output_path),
                        "download_url": f"/files/{output_path.name}",
                        "total_redactions": total,
                        "categories": dict(counts),
                        "image_only_or_low_text_pages": low_text_pages,
                    }
                )

        try:
            client_id = safe_client_id(client_id)
            zip_path = create_redacted_zip(results, output_root, client_id)
            upload_info = upload_zip_to_s3(
                zip_path,
                client_id,
                bucket=s3_bucket,
                region=aws_region,
            )
        except Exception as exc:
            raise HTTPException(
                status_code=500,
                detail=f"Redaction succeeded but ZIP/S3 upload failed: {exc}",
            ) from exc

        return {
            "count": len(results),
            "client_id": client_id,
            "output_paths": [item["output_path"] for item in results],
            "outputs": results,
            "zip_path": str(zip_path),
            "s3_bucket": upload_info["bucket"],
            "s3_key": upload_info["key"],
            "s3_uri": upload_info["s3_uri"],
        }

    @app.get("/files/{filename}")
    def get_redacted_file(filename: str):
        # Path.name removes directory traversal components such as ../
        safe_name = Path(filename).name
        target = (output_root / safe_name).resolve()
        if target.parent != output_root or not target.is_file() or target.suffix.lower() != ".pdf":
            raise HTTPException(status_code=404, detail="File not found.")
        return FileResponse(
            path=str(target),
            media_type="application/pdf",
            filename=target.name,
        )

    return app


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Fully local wealth-management PDF redactor. Process PDFs directly "
            "or expose a local HTTP API for other languages."
        )
    )
    parser.add_argument(
        "inputs",
        nargs="*",
        help="Input PDF(s). If omitted outside --serve, opens a local file picker.",
    )
    parser.add_argument(
        "--serve",
        action="store_true",
        help="Run the local HTTP API instead of processing command-line files.",
    )
    parser.add_argument(
        "--host",
        default="127.0.0.1",
        help="API bind address. Default 127.0.0.1 keeps the API local-only.",
    )
    parser.add_argument("--port", type=int, default=8765, help="API port (default: 8765).")
    parser.add_argument(
        "--output-dir",
        default="redacted_output",
        help="Directory for generated PDFs (default: ./redacted_output).",
    )
    parser.add_argument(
        "--client-id",
        default=DEFAULT_CLIENT_ID,
        help=(
            "Client/account ID used in the S3 path uploads/<client_id>/... "
            f"(default: {DEFAULT_CLIENT_ID})."
        ),
    )
    parser.add_argument(
        "--s3-bucket",
        default=DEFAULT_S3_BUCKET,
        help=f"S3 destination bucket (default: {DEFAULT_S3_BUCKET}).",
    )
    parser.add_argument(
        "--aws-region",
        default=DEFAULT_AWS_REGION,
        help=f"AWS region (default: {DEFAULT_AWS_REGION}).",
    )
    parser.add_argument(
        "--no-upload",
        action="store_true",
        help="Redact and create the ZIP locally, but do not upload it to S3.",
    )
    parser.add_argument("--password", help="Password for encrypted PDFs in CLI mode, if required.")
    parser.add_argument("--no-ner", action="store_true", help="Disable optional local spaCy PERSON detection.")
    parser.add_argument(
        "--padding",
        type=float,
        default=1.5,
        help="Extra black-box padding in PDF points (default: 1.5).",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()

    if args.serve:
        if args.inputs:
            print("Do not pass input PDFs with --serve. Upload them to POST /redact instead.", file=sys.stderr)
            return 2
        try:
            import uvicorn
        except ImportError:
            print(
                "API mode needs: pip install fastapi uvicorn python-multipart",
                file=sys.stderr,
            )
            return 2

        app = create_api_app(
            args.output_dir,
            no_ner=args.no_ner,
            padding=args.padding,
            s3_bucket=args.s3_bucket,
            aws_region=args.aws_region,
        )
        print(f"LocalRedact API: http://{args.host}:{args.port}")
        print(f"Interactive API docs: http://{args.host}:{args.port}/docs")
        print(f"Output directory: {Path(args.output_dir).expanduser().resolve()}")
        uvicorn.run(app, host=args.host, port=args.port, log_level="info")
        return 0

    inputs = list(args.inputs)
    if not inputs:
        selected = choose_file_gui()
        if not selected:
            print("No input PDF selected.", file=sys.stderr)
            return 2
        inputs = [selected]

    try:
        results = redact_files(
            inputs,
            args.output_dir,
            password=args.password,
            no_ner=args.no_ner,
            padding=args.padding,
        )
    except Exception as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    try:
        client_id = safe_client_id(args.client_id)
        zip_path = create_redacted_zip(results, args.output_dir, client_id)

        upload_info = None
        if not args.no_upload:
            upload_info = upload_zip_to_s3(
                zip_path,
                client_id,
                bucket=args.s3_bucket,
                region=args.aws_region,
            )
    except Exception as exc:
        print(f"Error creating/uploading redacted ZIP: {exc}", file=sys.stderr)
        return 1

    response = {
        "client_id": client_id,
        "output_paths": [r["output_path"] for r in results],
        "outputs": results,
        "zip_path": str(zip_path),
    }

    if upload_info:
        response.update(
            {
                "s3_bucket": upload_info["bucket"],
                "s3_key": upload_info["key"],
                "s3_uri": upload_info["s3_uri"],
            }
        )

    print(json.dumps(response, indent=2))

    for result in results:
        if result["image_only_or_low_text_pages"]:
            pages = ", ".join(map(str, result["image_only_or_low_text_pages"]))
            print(
                f"WARNING: {result['input_file']} has pages with little/no extractable text: {pages}. "
                "OCR or manual review may be required.",
                file=sys.stderr,
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
